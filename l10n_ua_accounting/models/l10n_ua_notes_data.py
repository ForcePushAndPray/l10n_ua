def notes_rows():
    """Every row of the form: (section, sequence, code, name, kind, graphs)."""
    rows = []
    seq = 0
    for number, title, graphs, _titles, lines in NOTES_SECTIONS:
        seq += 10
        rows.append((number, seq, '', f'{number}. {title}', 'section', ()))
        for code, name, kind, row_graphs in lines:
            seq += 10
            rows.append((number, seq, code, name, kind,
                         graphs if row_graphs is None else row_graphs))
    return rows


def notes_xml_element(code, graph):
    """R0010G3 — the element of J0901301 for a cell of the form.

    Rows below 1000 get a leading zero (010 → R0010), also the subrows of
    a three-digit row (2641, «264» + «1» → R02641); rows 1110–1540 do not."""
    prefix = '' if (len(code) == 4 and code.startswith('1')) else '0'
    return f'R{prefix}{code}G{graph}'
