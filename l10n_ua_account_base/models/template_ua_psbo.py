"""Доповнення стокового плану рахунків `ua_psbo` класом 0.

Стоковий `l10n_ua` везе 332 рахунки класів 1–9, але клас 0 «Позабалансові
рахунки» відсутній цілком. Без нього немає де вести орендовані необоротні
активи, ТМЦ на відповідальному зберіганні, видані та отримані гарантії й
бланки суворого обліку — а на них посилаються примітки до Ф1 та інвентаризація.

Джерело: План рахунків бухгалтерського обліку активів, капіталу, зобовʼязань і
господарських операцій підприємств і організацій, затверджений наказом
Мінфіну від 30.11.1999 № 291 (z0892-99), розділ «Клас 0. Позабалансові
рахунки». У самому Плані клас 0 наведено без субрахунків — Інструкція лишає їх
на розсуд підприємства, тож тут заводяться лише синтетичні рахунки 01–09.

Дані шаблонів зливаються по xmlid з усіх модулів (`chart_template.py:797`),
тому цей метод додає рахунки до стокових, а не заміщує їх.
"""
from odoo import models
from odoo.addons.account.models.chart_template import template


# (код, назва, ua_analytics_type). Аналітика 'partner' — там, де облік завжди
# ведеться в розрізі контрагента (орендодавець, поклажодавець, гарант). На 07,
# 08 і 09 предметом обліку є сам актив чи бланк, тому аналітики немає.
#
# Список використовує і post_init_hook — для баз, де локалізація стала раніше
# за цей модуль і шаблон уже відпрацював.
OFFBALANCE_ACCOUNTS = [
    ('01', 'Орендовані необоротні активи', 'partner'),
    ('02', 'Активи на відповідальному зберіганні', 'partner'),
    ('03', "Контрактні зобов'язання", 'partner'),
    ('04', "Непередбачені активи й зобов'язання", 'none'),
    ('05', 'Гарантії та забезпечення надані', 'partner'),
    ('06', 'Гарантії та забезпечення отримані', 'partner'),
    ('07', 'Списані активи', 'none'),
    ('08', 'Бланки суворого обліку', 'none'),
    ('09', 'Амортизаційні відрахування', 'none'),
]


class AccountChartTemplate(models.AbstractModel):
    _inherit = 'account.chart.template'

    @template('ua_psbo', 'account.account')
    def _get_ua_psbo_offbalance_account_account(self):
        return {
            f'ua_psbo_{code}': {
                'name': name,
                'code': code,
                'account_type': 'off_balance',
                'reconcile': False,
                'ua_analytics_type': analytics,
            }
            for code, name, analytics in OFFBALANCE_ACCOUNTS
        }
